"""``python -m hp``: inspect what the engine does to a pattern.

Four verbs, each one answering a question the README makes a claim about:

``compile``   what machine code does this pattern become?
``match``     do the three tiers agree on this subject?
``analyse``   what does the engine know before it builds anything?
``bench``     how fast is each tier on this machine, and Python's ``re``?

``compile`` is the one worth trying first, and it runs anywhere, the code is
generated and disassembled in pure Python, so a Windows laptop that cannot
execute a single generated byte still prints exactly what would be executed.
"""

import sys
import time

from . import engine as E
from .jit import codegen, memory, program as prog
from .re import dfa as D, nfa as N, parser as P

USAGE = """usage: python -m hp <command> [args]

  compile  <pattern> [--abi sysv|win64] [--raw]   generated x86-64, annotated
  match    <pattern> <subject>                    all three tiers, side by side
  analyse  <pattern>                              what the policy sees up front
  bench    <pattern> [bytes]                      per-tier throughput vs re
"""


def _search_dfa(pattern, minimize=True):
    node = P.unanchored(P.parse(pattern))
    dfa = D.build(N.build(node))
    return D.minimise(dfa) if minimize else dfa


def cmd_compile(argv):
    pattern = argv[0]
    abi = "sysv"
    minimize = True
    if "--abi" in argv:
        abi = argv[argv.index("--abi") + 1]
    if "--raw" in argv:
        minimize = False

    dfa = _search_dfa(pattern, minimize=minimize)
    code = codegen.compile_to_bytes(dfa, 0, abi=abi)
    print("pattern   %r" % pattern)
    print("searching %r  (the engine matches .*P.* entirely, which is the same\n"
          "          question as finding P anywhere, in one left-to-right pass)"
          % pattern)
    print()
    print(dfa.describe())
    print()
    print("generated %d bytes of x86-64 (%s ABI), %d byte classes"
          % (len(code), abi, dfa.n_classes))
    print()
    print(prog.listing_for(dfa, abi=abi))
    return 0


def cmd_match(argv):
    pattern, subject = argv[0], argv[1].encode()
    rows = []
    for tier in (E.TIER_BACKTRACK, E.TIER_DFA, E.TIER_JIT):
        p = E.Pattern(pattern, step_limit=2_000_000)
        if p.promote(tier) is None and tier > E.TIER_BACKTRACK \
                and p.tier < tier:
            rows.append((E.TIER_NAMES[tier], "unavailable: %s" % p.reason, 0))
            continue
        t0 = time.perf_counter_ns()
        got = p.matches(subject)
        rows.append((E.TIER_NAMES[p.tier], str(got),
                     time.perf_counter_ns() - t0))
        p.free()
    print("pattern %r  subject %r (%d bytes)" % (pattern, argv[1],
                                                 len(subject)))
    for name, got, ns in rows:
        print("  %-10s %-40s %9s" % (name, got, "%d ns" % ns if ns else ""))
    answers = {r[1] for r in rows if r[1] in ("True", "False")}
    print("  %s" % ("tiers agree" if len(answers) == 1
                    else "TIERS DISAGREE. This is a bug"))
    return 0 if len(answers) == 1 else 1


def cmd_analyse(argv):
    p = E.Pattern(argv[0])
    print("pattern              %r" % argv[0])
    print("ast nodes            %d" % p.ast_nodes)
    print("distinct classes     %d" % p.ast_classes)
    print("counted-repeat span  %d" % p.repeat_span)
    print("nfa states (static)  %d" % p.nfa_states)
    print("backtracking risk    %s" % ("YES. Nested or ambiguous unbounded "
                                       "repetition; this pattern must not be "
                                       "run on the backtracking tier"
                                       if p.risky else "no"))
    spent = p.promote(E.TIER_DFA)
    if p.dfa is None:
        print("dfa                  not built: %s" % p.reason)
        return 0
    raw = D.build(N.build(p.search_ast))
    print("dfa states           %d  (%d before minimisation)"
          % (len(p.dfa), len(raw)))
    print("dfa edges            %d" % p.dfa.n_edges())
    print("byte classes         %d" % p.dfa.n_classes)
    print("build cost           %.2f ms" % (spent / 1e6))
    print("code size            %d bytes" % codegen.code_size(p.dfa))
    p.free()
    return 0


def cmd_bench(argv):
    import re as pyre
    pattern = argv[0]
    n = int(argv[1]) if len(argv) > 1 else 65536
    filler = (b"the quick brown fox jumps over the lazy dog 10.0.0.1 "
              b"warning: nothing to see 2026-09-02 ")
    subject = (filler * (n // len(filler) + 2))[:n]

    dfa = _search_dfa(pattern)
    rows = [("python re", pyre.compile(pattern.encode()).search)]
    rows.append(("hotpath dfa", dfa.fullmatch))
    program = None
    if memory.available():
        program = prog.compile_dfa(dfa)
        rows.append(("hotpath jit", program))

    print("pattern %r over %d bytes" % (pattern, n))
    base = None
    for name, fn in rows:
        reps = max(3, 2_000_000 // max(n, 1))
        best = None
        for _ in range(5):
            t0 = time.perf_counter_ns()
            for _ in range(reps):
                fn(subject)
            took = (time.perf_counter_ns() - t0) / reps
            best = took if best is None else min(best, took)
        base = base or best
        print("  %-12s %10.0f ns  %7.2f ns/byte  %6.2fx python"
              % (name, best, best / n, base / best))
    if program:
        program.free()
    return 0


COMMANDS = {"compile": cmd_compile, "match": cmd_match,
            "analyse": cmd_analyse, "bench": cmd_bench}


def main(argv):
    if len(argv) < 2 or argv[1] not in COMMANDS:
        sys.stdout.write(USAGE)
        return 2
    try:
        return COMMANDS[argv[1]](argv[2:])
    except IndexError:
        sys.stdout.write(USAGE)
        return 2
    except P.ParseError as exc:
        sys.stderr.write("parse error: %s\n" % exc)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
